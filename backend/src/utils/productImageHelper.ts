export type FoodPhotoStyle = 'CAFE_WARM' | 'GOURMET_STUDIO' | 'COMMERCIAL_VIBRANT' | 'TRADITIONAL_RUSTIC';

/**
 * Generate photo URL based on item name and category
 */
export const generateProfessionalFoodImageUrl = (
  productName: string,
  category: string,
  options?: {
    style?: FoodPhotoStyle;
    seed?: number;
    customInstruction?: string;
  }
): string => {
  const cleanName = productName.replace(/[^a-zA-Z0-9 ]/g, '').trim();
  const cleanCat = category.replace(/[^a-zA-Z0-9 ]/g, '').trim();
  const catLower = (cleanCat + ' ' + cleanName).toLowerCase();
  const seed = options?.seed ?? 0;

  // Jika ada custom prompt khusus dari Studio Foto AI per-item
  if (options?.customInstruction) {
    const prompt = encodeURIComponent(`commercial professional culinary photography of ${cleanName}, ${options.customInstruction.trim()}, 8k photorealistic, clean food styling`);
    return `https://image.pollinations.ai/prompt/${prompt}?width=400&height=400&seed=${seed}&nologo=true`;
  }

  let pool = CURATED_FOOD_IMAGES.rice_bowl;

  if (/\b(ramen|udon|mie|soba|noodle|noodles|kuah|pasta|spaghetti|curry)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.ramen_noodle;
  } else if (/\b(kopi|coffee|espresso|cappuccino|latte|americano|black|aren|butterscotch|caramel|hazelnut|pandan)\b/i.test(catLower)) {
    if (/\b(dingin|ice|iced|frappe|cold)\b/i.test(catLower) || cleanName.toLowerCase().startsWith('ice')) {
      pool = CURATED_FOOD_IMAGES.coffee_cold;
    } else {
      pool = CURATED_FOOD_IMAGES.coffee_hot;
    }
  } else if (/\b(teh|tea|matcha|lemon tea|lychee tea|chocolate|cokelat)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.tea_matcha;
  } else if (/\b(drink|drinks|mocktail|beverage|beverages|juice|jus|soda|boba|smoothie|yakult)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.drink_mocktail;
  } else if (/\b(ayam|chicken|katsu|karage|karaage|daging|beef|steak|gyu|teriyaki|slice)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.chicken_meat;
  } else if (/\b(snack|snacks|cireng|kentang|fries|dimsum|gyoza|tempura|tofu|nori|odeng|bites|topping)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.snack_bites;
  } else if (/\b(roti|toast|croissant|pastry|bakery|cake|tart|churros|waffle|pancake|dessert|sweet|donut|donat|ice cream|gelato)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.pastry_dessert;
  } else if (/\b(nasi|rice|bowl|goreng|salmon)\b/i.test(catLower)) {
    pool = CURATED_FOOD_IMAGES.rice_bowl;
  }

  const hash = Math.abs(cleanName.split('').reduce((acc, char) => acc + char.charCodeAt(0), seed));
  return pool[hash % pool.length];
};

